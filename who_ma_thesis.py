def preprocess_text_spacy(text):
  """Cleans, lemmatizes, and removes stopwords using spaCy to feed into

  the BERTopic embedding pipeline.
  """
  if not text:
    return ""
  doc = nlp(text)
  tokens = [
      token.lemma_
      for token in doc
      if not token.is_stop and not token.is_punct and not token.like_num
  ]
  return " ".join(tokens)


