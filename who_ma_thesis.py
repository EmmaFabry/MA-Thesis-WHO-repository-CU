def clean_and_extract(file_path):
  """Extracts raw text from PDF documents and normalises whitespace/case while

  strictly preserving hyphens and multi-word phrases for regex evaluation.
  """
  try:
    import fitz

    with fitz.open(file_path) as doc:
      text = " ".join([page.get_text("text") for page in doc])
      clean_text = text.replace(file_path.stem.replace("_", " "), "")
      clean_text = clean_text.lower()
      clean_text = re.sub(r"\s+", " ", clean_text).strip()
      return clean_text
  except Exception as e:
    print(f"Error in text extraction for {file_path.name}: {e}")
    return None


def get_word_count(text):
  return len(text.split()) if text else 0


def analyze_text(text, word_count):
  """Computes word-boundary-safe regex matches for each track, normalised per 10,000 words."""
  if not text or word_count == 0:
    return pd.Series([0.0, 0.0, 0.0])

  multiplier = 10000 / word_count

  def count_pattern(kw_list):
    total_matches = 0
    for kw in kw_list:
      pattern = r"\b" + re.escape(kw) + r"\b"
      total_matches += len(re.findall(pattern, text))
    return total_matches * multiplier

  tech_score = count_pattern(technical_keywords)
  moral_score = count_pattern(moral_keywords)
  uncert_score = count_pattern(uncertainty_diagnostics)

  return pd.Series([tech_score, moral_score, uncert_score])


def extract_kwic_contexts(text, keyword, window=7):
  """Finds every word-boundary-safe occurrence of `keyword` in the full text

  and returns context windows of `window` words on each side.
  """
  if not text:
    return []
  contexts = []
  pattern = r"\b" + re.escape(keyword) + r"\b"
  for match in re.finditer(pattern, text):
    start_char, end_char = match.span()
    before_words = text[:start_char].split()[-window:]
    after_words = text[end_char:].split()[:window]
    context = (
        f"{' '.join(before_words)} [{keyword.upper()}] {' '.join(after_words)}"
    )
    contexts.append(context)
  return contexts


def build_master_corpus(base_folder):
  """Crawls nested subdirectories systematically, extracting text from PDFs

  and preparing both raw text (for KWIC/dictionary analysis) and preprocessed
  text (for BERTopic).
  """
  base_path = Path(base_folder)
  pdf_files = list(base_path.glob("**/*.pdf"))

  print(
      f"Discovered {len(pdf_files)} PDF items across folder architecture."
      " Commencing extraction..."
  )

  target_categories = [
      "_SituationReports",
      "_InterimGuidelines",
      "_Statements",
      "_StrategicPlans",
      "_DirectorGeneral",
      "_AFRO",
      "_EMRO",
      "_EURO",
      "_PAHO",
      "_SEARO",
      "_WPRO",
  ]

  all_records = []
  skipped_no_category = 0

  for f in pdf_files:
    assigned_category = None
    for parent in f.parents:
      if parent.name in target_categories:
        assigned_category = parent.name.replace("_", "")
        break

    if not assigned_category:
      skipped_no_category += 1
      continue

    if assigned_category in ["AFRO", "EMRO", "EURO", "PAHO", "SEARO", "WPRO"]:
      assigned_category = f"Speeches_{assigned_category}"
    elif assigned_category == "DirectorGeneral":
      assigned_category = "DG_Speeches"

    date_match = re.search(r"(\d{4}-\d{2}-\d{2})", f.stem)
    if date_match:
      doc_date = pd.to_datetime(date_match.group(1))
      doc_year = doc_date.year

      if 2020 <= doc_year <= 2023:
        content = clean_and_extract(f)
        if content and len(content.split()) > 10:
          processed_text = preprocess_text_spacy(content)
          all_records.append({
              "date": doc_date,
              "year": doc_year,
              "category": assigned_category,
              "filename": f.stem,
              "text": content,
              "processed_text": processed_text,
              "word_count": get_word_count(content),
          })

  master_df = pd.DataFrame(all_records)
  print(
      f"Ingestion engine complete. Successfully processed {len(master_df)}"
      " documents."
  )
  if skipped_no_category:
    print(
        f"Note: {skipped_no_category} PDF(s) had no matching category folder in"
        " their path and were skipped."
    )
  return master_df


